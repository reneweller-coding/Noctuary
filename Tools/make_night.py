"""Noctuary -- what the night director (Core/include/ambient/NightDirector.h) needs of the library, into
Core/src/NightDirector.inc.

The director writes a whole night as a journey with a form (falling asleep, a deep middle in waves, a morning) along a
curve of stillness and brightness, every crossfade a step to something that measures alike. All of it comes from the
library's own measurement, the one the journey templates are made from (work/library/packs.json, Tools/make_journeys.py;
a 60 s render of every pack preset, Tools/library/map_all.py):

  stillness   how much the sound moves, from the moment to the minute: the mean of three standardised measures --
              the spectral flux (the moment), the level's evolution over the minute (log1p evo_level) and the tone's
              (evo_tone). Lower is stiller. The brightness is NOT in it (make_journeys.py's Night order counts the
              centroid in its stillness; here it is the curve's other axis, and with it in both, the two axes of a
              night would move as one).
  brightness  the spectral centroid, log (the map's Bright is its rank).
  roughness   Plomp-Levelt roughness of the preset's own spectrum: the director keeps the rough ones out of the falling
              asleep and the deep.
  moving      how much a preset moves by itself over the minute, make_journeys.timings()'s measure
              (log1p evo_level + 2 evo_tone): what a step's length is made of.
  features    make_journeys.features(), standardised over the whole library (the crossings' scale): the 18 numbers a
              journey's "sounds alike" is measured in -- centroid, flatness, flux, bass, width, the two evolutions,
              level, roughness, wet and eight timbre bands. Stored as round(z * 20) in a signed byte (z clamped to
              +-6.35), so the distance the director measures is the journeys' Euclidean distance to within a few
              hundredths of a spread.

The first four as z-scores over the library in thousandths (the director ranks them over its candidates); the packs
with the family make_journeys.py gives them (the artists' families: sleep, deep, ritual, cold, British, luminous,
space).

    python Tools/make_night.py            # writes Core/src/NightDirector.inc
    python Tools/make_night.py --check    # compares, writes nothing (exit 1 when different)
"""
import argparse
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
OUT = os.path.join(ROOT, "Core", "src", "NightDirector.inc")
sys.path.insert(0, HERE)
import make_journeys  # noqa: E402

FEATURE_SCALE = 20.0   # a byte step is 1/20 of a spread


def zscores(values):
    """The values as z-scores (population spread; a constant column stays 0)."""
    n = len(values)
    mean = sum(values) / n
    sd = math.sqrt(sum((v - mean) ** 2 for v in values) / n) or 1.0
    return [(v - mean) / sd for v in values]


def build(cache):
    """The text of NightDirector.inc from the measurement cache."""
    packs = make_journeys.pack_presets()
    fams = make_journeys.pack_families()
    titles = list(packs)
    names, owner, vecs = [], [], []
    for p, title in enumerate(titles):
        for name in packs[title]:
            row = cache.get(name)
            if row is None:
                continue
            names.append(name)
            owner.append(p)
            vecs.append(make_journeys.features(row))
    z = make_journeys.standardise(vecs)
    rows = [cache[n] for n in names]
    flux = zscores([r.get("flux", 0.5) for r in rows])
    evl = zscores([math.log1p(max(r.get("evo_level", 1.0), 0.0)) for r in rows])
    evt = zscores([r.get("evo_tone", 0.3) for r in rows])
    still = [(a + b + c) / 3.0 for a, b, c in zip(flux, evl, evt)]
    bright = zscores([math.log(max(r.get("centroid", 500.0), 30.0)) for r in rows])
    rough = zscores([r.get("rough", 0.01) for r in rows])
    moving = zscores([math.log1p(max(r.get("evo_level", 1.6), 0.0)) + 2.0 * r.get("evo_tone", 0.42) for r in rows])

    def esc(s):
        return s.replace("\\", "\\\\").replace('"', '\\"')

    def milli(v):
        return max(-32767, min(32767, int(round(v * 1000.0))))

    def byte(v):
        return max(-127, min(127, int(round(v * FEATURE_SCALE))))

    lines = ["// Generated by Tools/make_night.py from work/library/packs.json -- do not edit; edit the script and run it",
             "// again. %d presets of %d packs." % (len(names), len(titles)),
             "/// The night director's packs: the pack's title and its family (make_journeys.py's).",
             "const NightPackS NightPacks[] = {"]
    for title in titles:
        lines.append('    { "%s", "%s" },' % (esc(title), esc(fams.get(title, "sleep"))))
    lines += ["};",
              "/// Per measured preset: its name, its pack (NightPacks), stillness, brightness, roughness and its own",
              "/// motion as z-scores over the library in thousandths, and the journeys' 18 features standardised over the",
              "/// library, x %g." % FEATURE_SCALE,
              "const NightRowS NightRows[] = {"]
    for i, name in enumerate(names):
        lines.append('{"%s",%d,%d,%d,%d,%d,{%s}},' % (
            esc(name), owner[i], milli(still[i]), milli(bright[i]), milli(rough[i]), milli(moving[i]),
            ",".join(str(byte(v)) for v in z[i])))
    lines.append("};")
    return "\n".join(lines) + "\n", len(names), len(titles)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--cache", default=os.path.join(ROOT, "work", "library", "packs.json"))
    ap.add_argument("--check", action="store_true", help="compare with the file in the tree, write nothing")
    a = ap.parse_args()
    if not os.path.exists(a.cache):
        # The measurement lies in work/ (not in the repository): without it there is nothing to compare with.
        print("make_night: no measurement at %s -- nothing to check (skipped)" % a.cache)
        return 77 if a.check else 1
    with open(a.cache, encoding="utf-8") as f:
        cache = json.load(f)
    text, n, p = build(cache)
    data = text.encode("utf-8")
    if a.check:
        old = open(OUT, "rb").read() if os.path.exists(OUT) else b""
        if old != data:
            print("make_night: %s is DIFFERENT from what the measurement makes" % OUT)
            return 1
        print("make_night: %s is what the measurement makes (%d presets, %d packs)" % (OUT, n, p))
        return 0
    with open(OUT, "wb") as f:
        f.write(data)
    print("%d presets of %d packs -> %s (%d kB)" % (n, p, OUT, len(data) // 1024))
    return 0


if __name__ == "__main__":
    sys.exit(main())
