"""Sort the Room's impulse library: keep what is a space fit for ambient work, move the rest out.

Library/Impulses was generated by make_impulses.py. Two of its families were cut from the sample
library -- `struck` (a strike taken from a clip, 0.1-0.45 s) and `space` (a slice of a texture or
field recording with a decay laid over it) -- and are colours of those clips rather than rooms.
Several designed families ring at fixed pitches (tuned, chord, comb, modal_*, tube, sheet) or are
sparse taps (echoes, scatter): as a reverb they fight the key, and the instrument has better tools
for both -- the Cloud's scale resonators, Body and Sympathy follow the key, the two delays the
tempo. The rest (room_*, diffusion, spectral, the longer reverse swells, the darker shimmers) stay
unless a measurement says otherwise.

Nothing is deleted: rejected files move to --out with a manifest (reasons, measurements, how many
pack presets name the file), and --restore puts them back. The packs are not touched; a preset
naming a file that went keeps whatever impulse the Room already had (the plugin skips a missing
file) until the packs are rebuilt.

  python Tools/library/curate_impulses.py [--dry-run] [--out DIR]
  python Tools/library/curate_impulses.py --restore [--out DIR]
"""
import argparse
import collections
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
IMPULSES = os.path.join(ROOT, "Library", "Impulses")
PACKS = os.path.join(ROOT, "Library", "Packs")
DEFAULT_OUT = os.path.normpath(os.path.join(ROOT, "..", "_Sources", "IRSources", "rejected-generated"))

sys.path.insert(0, HERE)
import ir_metrics  # noqa: E402

FAMILY_VERDICT = {
    "struck": "cut from a clip of the sample library: a strike of 0.1-0.45 s, a colour of that clip rather than a space",
    "space": "cut from a texture or field recording with a decay laid over it: the clip's content smeared, not a room",
    "tuned": "rings at fixed pitches and fights every other key; the Cloud's scale resonators follow the key",
    "chord": "a chord of combs: metallic, fixed pitches, clicks",
    "comb": "a comb, a flutter echo: metallic",
    "modal_bell": "fixed bell modes: a pitched object, not a space",
    "modal_plate": "fixed plate modes: a pitched object, not a space",
    "modal_spring": "fixed spring modes: a pitched object, not a space",
    "tube": "one fixed tube resonance",
    "sheet": "a few fixed sheet-metal modes",
    "echoes": "a handful of discrete echoes: a slapback; the delays do that in tempo",
    "scatter": "sparse bright taps: grit rather than a tail",
    "underwater": "a low-passed rumble; Tail Cut on any room gives the same",
}


def family(name):
    return re.sub(r"(_\d+)?\.wav$", "", name)


def pack_references():
    refs = collections.Counter()
    for p in sorted(os.listdir(PACKS)):
        if not p.endswith(".ambientpack"):
            continue
        with open(os.path.join(PACKS, p), encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if line.startswith("#") or "|" not in line:
                    continue
                f = line.rstrip("\n").split("|")
                for field in (5, 8):   # impulse A, and impulse B since packs carry one
                    if len(f) > field and f[field].strip():
                        refs[f[field].strip().split("/")[-1]] += 1
    return refs


def verdict(m):
    fam = family(m["file"])
    if fam in FAMILY_VERDICT:
        return [FAMILY_VERDICT[fam]]
    why = []
    centroid = m.get("centroid_hz") or 0.0
    lf = m.get("lf_db") if m.get("lf_db") is not None else -99.0
    t30 = m.get("t30") or 0.0
    if centroid > 7000.0:
        why.append(f"hiss: power centroid at {centroid / 1000.0:.1f} kHz")
    if fam.startswith("room_") or fam == "diffusion":
        if lf > -3.0:
            why.append(f"mud: {lf:.0f} dB of its energy below 150 Hz")
        if t30 < 1.0:
            why.append(f"too short for a space: T30 {t30:.1f} s")
    if fam == "spectral" and (m.get("env_resid_db") or 0.0) > 4.0:
        why.append("an uneven decay")
    if fam == "reverse" and (m.get("seconds") or 0.0) < 1.5:
        why.append("too short to swell")
    if (m.get("jump") or 0.0) > 60.0:
        why.append("a click in it")
    return why


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--restore", action="store_true")
    args = ap.parse_args()
    manifest_path = os.path.join(args.out, "manifest.json")
    previous = []
    if os.path.exists(manifest_path):
        with open(manifest_path, encoding="utf-8") as fh:
            previous = json.load(fh).get("rejected", [])
    if args.restore:
        n = 0
        for row in previous:
            src = os.path.join(args.out, row["file"])
            if os.path.exists(src):
                shutil.move(src, os.path.join(IMPULSES, row["file"]))
                n += 1
        os.remove(manifest_path)
        print(f"restored {n} impulses to {IMPULSES}")
        return
    files = sorted(f for f in os.listdir(IMPULSES) if f.lower().endswith(".wav"))
    refs = pack_references()
    kept, rejected = [], []
    for i, f in enumerate(files):
        try:
            m = ir_metrics.analyse(os.path.join(IMPULSES, f))
            why = ["silent"] if m.get("silent") else verdict(m)
        except Exception as exc:   # unreadable is a reason too
            m, why = {"file": f, "error": str(exc)}, ["unreadable"]
        row = {"file": f, "family": family(f), "presets": refs.get(f, 0), "reasons": why, "metrics": m}
        (rejected if why else kept).append(row)
        if (i + 1) % 100 == 0:
            print(f"{i + 1}/{len(files)}", flush=True)
    per = collections.defaultdict(lambda: [0, 0])
    for r in kept:
        per[r["family"]][0] += 1
    for r in rejected:
        per[r["family"]][1] += 1
    for fam, (k, r) in sorted(per.items(), key=lambda kv: -sum(kv[1])):
        print(f"  {fam:16s} keep {k:3d}  out {r:3d}")
    print(f"keep {len(kept)}, out {len(rejected)}; pack presets naming a file that goes: "
          f"{sum(r['presets'] for r in rejected)} (naming one that stays: {sum(r['presets'] for r in kept)})")
    if args.dry_run:
        return
    os.makedirs(args.out, exist_ok=True)
    for r in rejected:
        shutil.move(os.path.join(IMPULSES, r["file"]), os.path.join(args.out, r["file"]))
    merged = {row["file"]: row for row in previous}
    merged.update({row["file"]: row for row in rejected})
    with open(manifest_path, "w", encoding="utf-8") as fh:
        json.dump({"library": IMPULSES, "kept": kept, "rejected": list(merged.values())}, fh, indent=1)
    print(f"moved {len(rejected)} files to {args.out}; manifest {manifest_path}")


if __name__ == "__main__":
    main()
