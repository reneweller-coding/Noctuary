bool loadPresetPack( const char *path )
{
    if ( path == nullptr ) return false;
    // Loading the same file twice is doing nothing, not doing it twice. The default folders have
    // always been documented that way ("a pack found twice loads once") but the guard was only in
    // the folder scan, so a second call with the same path appended every preset again. It is what
    // lets one process render preset after preset (ambient_render --batch) without the library
    // growing under it.
    {
        std::error_code ec;
        std::string     key = std::filesystem::weakly_canonical( std::filesystem::path( path ), ec ).string();
        if ( ec ) key = path;
        auto &seen = loadedPaths();
        if ( std::find( seen.begin(), seen.end(), key ) != seen.end() ) return false;
    }
    std::ifstream f( path );
    if ( !f ) return false;
    Pack pack;
    int  format = 1;   // no "format" line: written before the classic wavetable (see migrateFormat1)
    pack.m_dir = std::filesystem::path( path ).parent_path().string();
    pack.m_name = std::filesystem::path( path ).stem().string();
    std::string line;
    while ( std::getline( f, line ) )
    {
        const std::string t = trim( line );
        if ( t.empty() || t[0] == '#' ) continue;
        if ( t.rfind( "pack ", 0 ) == 0 )
        {
            pack.m_name = trim( t.substr( 5 ) );
            continue;
        }
        if ( t.rfind( "format ", 0 ) == 0 && t.find( '|' ) == std::string::npos )
        {
            format = std::atoi( t.substr( 7 ).c_str() );
            continue;
        }
        const std::vector<std::string> fields = split( t, '|' );
        if ( fields.size() < 2 ) return false;
        PackEntry e;
        e.m_name = trim( fields[0] );
        e.m_settings = format < 2 ? migrateFormat1( trim( fields[1] ) ) : trim( fields[1] );
        if ( e.m_name.empty() ) return false;
        if ( fields.size() > 2 )
        {   // x y bright motion width noisy bass density tagbits
            const std::vector<std::string> m = split( trim( fields[2] ), ' ' );
            float                          v[8] = { 0.5f, 0.5f, 0.5f, 0.5f, 0.5f, 0.5f, 0.5f, 0.5f };
            size_t                         j = 0;
            for ( const std::string &tok : m )
            {
                if ( tok.empty() ) continue;
                if ( j < 8 )
                    v[j] = static_cast<float>( std::atof( tok.c_str() ) );
                else if ( j == 8 )
                    e.m_meta.m_tags = static_cast<uint32_t>( std::strtoul( tok.c_str(), nullptr, 0 ) );
                else if ( j == 9 )
                    e.m_meta.m_loudDb =
                        static_cast<float>( std::atof( tok.c_str() ) );   // optional: older packs have none
                else if ( j == 10 )
                    e.m_meta.m_evolve =
                        static_cast<float>( std::atof( tok.c_str() ) );   // the drone descriptors, added in 1.11.0
                else if ( j == 11 )
                    e.m_meta.m_rough = static_cast<float>( std::atof( tok.c_str() ) );
                else if ( j == 12 )
                    e.m_meta.m_wet = static_cast<float>( std::atof( tok.c_str() ) );
                else if ( j == 13 )
                    e.m_meta.m_phrase[0] = static_cast<short>( std::atoi( tok.c_str() ) );   // what it sounds like,
                else if ( j == 14 )
                    e.m_meta.m_phrase[1] = static_cast<short>( std::atoi( tok.c_str() ) );   // chosen by CLAP
                else if ( j == 15 )
                    e.m_meta.m_cluster =
                        static_cast<short>( std::atoi( tok.c_str() ) );   // the group it was laid out in
                ++j;
            }
            e.m_meta.m_x = v[0];
            e.m_meta.m_y = v[1];
            e.m_meta.m_bright = v[2];
            e.m_meta.m_motion = v[3];
            e.m_meta.m_width = v[4];
            e.m_meta.m_noisy = v[5];
            e.m_meta.m_bass = v[6];
            e.m_meta.m_density = v[7];
        }
        if ( fields.size() > 3 ) e.m_texture = trim( fields[3] );
        if ( fields.size() > 4 ) e.m_wavetable = trim( fields[4] );
        if ( fields.size() > 5 ) e.m_impulse = trim( fields[5] );
        if ( fields.size() > 6 ) e.m_mod = trim( fields[6] );
        if ( fields.size() > 7 ) e.m_envs = trim( fields[7] );
        if ( fields.size() > 8 ) e.m_impulseB = trim( fields[8] );   // the impulse Room Morph goes to
        pack.m_entries.push_back( std::move( e ) );
    }
    if ( pack.m_entries.empty() ) return false;
    // The same pack can sit in two of the searched folders at once -- one copy put there by the
    // installer for everybody, one in the user's own Documents. Loading it twice would double
    // every preset in it, so the first one found wins.
    for ( const auto &have : packs() )
        if ( have->m_name == pack.m_name ) return false;
    // Every preset of a pack belongs to that pack's family, appended after the built-in families.
    const int family = builtinPresetFamilyCount() + static_cast<int>( packs().size() );
    for ( PackEntry &e : pack.m_entries ) e.m_meta.m_family = family;
    packs().push_back( std::make_unique<Pack>( std::move( pack ) ) );
    appendViews( *packs().back() );
    // Remembered as loaded only now that it is. Remembered at the top, a pack that failed to
    // parse -- or was simply not there yet -- could never be tried again in this process.
    {
        std::error_code ec;
        std::string     key = std::filesystem::weakly_canonical( std::filesystem::path( path ), ec ).string();
        if ( ec ) key = path;
        loadedPaths().push_back( key );
    }
    return true;
}

int loadPresetPacksIn( const char *dir )
{
    if ( dir == nullptr ) return 0;
    std::error_code ec;
    if ( !std::filesystem::is_directory( dir, ec ) ) return 0;
    std::vector<std::string> files;
    for ( const auto &entry : std::filesystem::directory_iterator( dir, ec ) )
        if ( entry.is_regular_file( ec ) && entry.path().extension() == ".ambientpack" )
            files.push_back( entry.path().string() );
    std::sort( files.begin(), files.end() );   // packs load in a stable order, so preset indices are reproducible
    int n = 0;
    for ( const std::string &f : files )
        if ( loadPresetPack( f.c_str() ) ) ++n;
    if ( n > 0 ) loadedFolders().push_back( { dir, readLibraryStamp( dir ), "" } );
    return n;
}

LibraryStampS readLibraryStamp( const char *folder )
{
    LibraryStampS s;
    if ( folder == nullptr ) return s;
    std::ifstream in( std::filesystem::path( folder ) / "library.stamp" );
    for ( std::string line; std::getline( in, line ); )
    {
        while ( !line.empty() && ( line.back() == '\r' || line.back() == ' ' ) ) line.pop_back();
        if ( line.rfind( "date=", 0 ) == 0 ) s.m_date = line.substr( 5 );
        if ( line.rfind( "hash=", 0 ) == 0 ) s.m_hash = line.substr( 5 );
    }
    return s;
}

LibraryStampS builtLibraryStamp()
{
    return { AMBIENT_LIBRARY_DATE, AMBIENT_LIBRARY_HASH };
}

bool libraryIsOlder( const LibraryStampS &loaded, const LibraryStampS &built )
{
    if ( built.m_date.empty() ) return false;                                  // built without a library: nothing to say
    if ( !built.m_hash.empty() && loaded.m_hash == built.m_hash ) return false;   // the very one
    if ( loaded.m_date.empty() ) return true;   // no stamp: from before 20.11.2026, so older than any build that has one
    return loaded.m_date < built.m_date;        // "YYYY-MM-DD hh:mm" sorts as text
}

std::string repoLibraryFor( const char *programPath )
{
    if ( programPath == nullptr || *programPath == 0 ) return {};
    std::error_code       ec;
    std::filesystem::path p = std::filesystem::path( programPath ).parent_path();
    for ( int up = 0; up < 8 && !p.empty(); ++up )
    {
        std::string name = p.filename().string();
        for ( char &c : name ) c = static_cast<char>( std::tolower( static_cast<unsigned char>( c ) ) );
        if ( name == "bin" )
        {
            const std::filesystem::path lib = p.parent_path() / "Library" / "Packs";
            if ( std::filesystem::is_directory( lib, ec ) )
                for ( const auto &entry : std::filesystem::directory_iterator( lib, ec ) )
                    if ( entry.is_regular_file( ec ) && entry.path().extension() == ".ambientpack" ) return lib.string();
        }
        const std::filesystem::path parent = p.parent_path();
        if ( parent == p ) break;
        p = parent;
    }
    return {};
}

std::string programPath()
{
#if defined( _WIN32 )
    // The module this code is linked into -- the exe, or the plug-in's DLL inside a host -- not the host's exe.
    HMODULE module = nullptr;
    if ( !GetModuleHandleExW( GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT,
                              reinterpret_cast<LPCWSTR>( &programPath ), &module ) )
        return {};
    std::wstring buf( 32768, L'\0' );
    const DWORD  len = GetModuleFileNameW( module, buf.data(), static_cast<DWORD>( buf.size() ) );
    if ( len == 0 || len >= buf.size() ) return {};
    buf.resize( len );
    return std::filesystem::path( buf ).string();
#elif defined( __linux__ )
    std::error_code ec;
    const auto      p = std::filesystem::read_symlink( "/proc/self/exe", ec );
    return ec ? std::string() : p.string();
#else
    return {};
#endif
}

LibraryStatusS libraryStatus()
{
    LibraryStatusS s;
    s.m_built = builtLibraryStamp();
    const auto &folders = loadedFolders();
    if ( folders.empty() ) return s;
    // The first folder that had packs is "the library"; an older one anywhere among them is the one to name.
    const LoadedFolder *pick = &folders.front();
    for ( const auto &f : folders )
        if ( libraryIsOlder( f.m_stamp, s.m_built ) )
        {
            pick = &f;
            break;
        }
    s.m_folder = pick->m_folder;
    s.m_how = pick->m_how;
    s.m_stamp = pick->m_stamp;
    s.m_older = libraryIsOlder( pick->m_stamp, s.m_built );
    return s;
}

std::string libraryNotice()
{
    const LibraryStatusS s = libraryStatus();
    if ( !s.m_older ) return {};
    return "OLD LIBRARY: " + s.m_folder + " (" + ( s.m_stamp.m_date.empty() ? std::string( "no stamp" ) : s.m_stamp.m_date ) +
           "), this build has the one of " + s.m_built.m_date;
}

